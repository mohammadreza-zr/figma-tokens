import type { Tree } from "./clean.js";
import type { ResolvedConfig } from "./config.js";
import { kebab } from "./css.js";

const pick = (node: unknown, name: string): Tree | undefined => {
  if (!node || typeof node !== "object") return undefined;
  const tree = node as Tree;
  const key = Object.keys(tree).find(
    (k) => k.toLowerCase() === name.toLowerCase(),
  );
  return key ? tree[key] : undefined;
};

const isToken = (v: unknown): v is Tree =>
  !!v && typeof v === "object" && "$value" in (v as object);

function leaves(node: unknown, prefix: string[] = [], out: string[][] = []) {
  if (!node || typeof node !== "object") return out;
  for (const [k, v] of Object.entries(node as Tree)) {
    if (isToken(v)) out.push([...prefix, k]);
    else if (v && typeof v === "object") leaves(v, [...prefix, k], out);
  }
  return out;
}

export function buildTailwind(merged: Tree, config: ResolvedConfig): string {
  const { semantic, primitives } = config;

  let rawBlock = "";
  (function register(node: Tree, prefix: string[] = []) {
    for (const [k, v] of Object.entries(node)) {
      if (isToken(v)) {
        const p = [...prefix, k];
        const seg = p.map((s) => s.toLowerCase());
        const isPrimitive =
          seg[0] === "color" && seg[1] === primitives.group.toLowerCase();
        if (isPrimitive && !primitives.keep.includes(seg[2])) continue;
        rawBlock += `  --${kebab(p)}: var(--${kebab(p)});\n`;
      } else if (v && typeof v === "object") register(v, [...prefix, k]);
    }
  })(merged);

  const semanticRoot = pick(pick(merged, "color"), semantic.group);
  const light = pick(semanticRoot, semantic.light) ?? {};
  const dark = pick(semanticRoot, semantic.dark) ?? {};
  const lightPrefix = kebab(["color", semantic.group, semantic.light]);
  const darkPrefix = kebab(["color", semantic.group, semantic.dark]);

  const darkNames = new Set(leaves(dark).map((p) => kebab(p)));

  let rootBlock = "";
  let darkBlock = "";
  let semBlock = "";
  for (const p of leaves(light)) {
    const name = kebab(p);
    rootBlock += `  --color-${name}: var(--${lightPrefix}-${name});\n`;
    darkBlock += darkNames.has(name)
      ? `  --color-${name}: var(--${darkPrefix}-${name});\n`
      : `  /* --color-${name}: no dark token in Figma — keeps light value */\n`;
    semBlock += `  --color-${name}: var(--color-${name});\n`;
  }

  const aliasBlock = Object.entries(config.aliases)
    .map(([a, t]) => `  --color-${a}: var(--color-${t});`)
    .join("\n");

  const sizeBlock = leaves(pick(merged, "size") ?? {})
    .map((p) => `  --text-${kebab(p)}: var(--size-${kebab(p)});`)
    .join("\n");

  const durationBlock = leaves(pick(merged, "duration") ?? {})
    .map(
      (p) =>
        `  --transition-duration-${kebab(p)}: var(--duration-${kebab(p)});`,
    )
    .join("\n");

  const fontRoot = config.fontSans
    ? `  --font-sans: var(--${config.fontSans});\n`
    : "";
  const fontTheme = config.fontSans ? "  --font-sans: var(--font-sans);\n" : "";

  const theme = [
    semBlock.trimEnd(),
    aliasBlock,
    sizeBlock,
    durationBlock,
    config.extra.replace(/^(\s*\n)+/, "").trimEnd(),
  ]
    .filter(Boolean)
    .join("\n");

  const sections: string[] = [
    "/** AUTO-GENERATED by figma-tokens — do not edit. */",
    `/* 1 ─ raw tokens → utilities (primitives: ${primitives.keep.join("/") || "none"}) */\n@theme inline {\n${rawBlock}}`,
  ];
  if (rootBlock || fontRoot) {
    sections.push(
      `/* 2 ─ semantic layer: light by default, flips under ${config.darkSelector} */\n${config.selector} {\n${rootBlock}${fontRoot}}`,
    );
  }
  if (darkBlock) sections.push(`${config.darkSelector} {\n${darkBlock}}`);
  if (theme || fontTheme) {
    sections.push(
      `/* 3 ─ semantic names → utilities */\n@theme inline {\n${theme ? `${theme}\n` : ""}${fontTheme}}`,
    );
  }
  return `${sections.join("\n\n")}\n`;
}
